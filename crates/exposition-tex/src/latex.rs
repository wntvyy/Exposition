/// Escape text typed on the page for insertion into LaTeX source at a
/// position of the given mode, so it typesets as the typed characters.
///
/// Text mode escapes TeX specials (`\ { } $ & % # _ ~ ^`). Math mode keeps
/// letters, digits, and ASCII operators, escapes specials, and turns typed
/// Greek letters and operators into macros (`α` → `\alpha `). Other Unicode
/// is passed through: LuaLaTeX accepts it; pdfLaTeX accepts what the
/// document's input encoding supports.
pub fn escape_insertion(text: &str, mode: Mode) -> String {
    escape_insertion_after(text, mode, None)
}

/// [`escape_insertion`] for text typed right after the character `before`
/// (which decides between an opening and a closing quotation mark).
///
/// In prose, characters that the default OT1 font encoding of pdfLaTeX
/// typesets as other glyphs are inserted as commands every encoding (OT1, T1,
/// TU) shows as typed: `<` `>` `|` become `\textless{}` `\textgreater{}`
/// `\textbar{}`. OT1 has no straight double quote at all (and
/// `\textquotedbl` is an error there), so `"` becomes TeX's opening ``` `` ```
/// at the start of a word and closing `''` otherwise, as LaTeX typesets
/// quotations in every engine.
pub fn escape_insertion_after(text: &str, mode: Mode, before: Option<char>) -> String {
    let mut out = String::with_capacity(text.len());
    let mut previous = before;
    for c in text.chars() {
        let opening =
            previous.is_none_or(|p| p.is_whitespace() || matches!(p, '(' | '[' | '{' | '~' | '“' | '‘' | '`'));
        previous = Some(c);
        match (mode, c) {
            (Mode::Text, '\\') => out.push_str("\\textbackslash{}"),
            (Mode::Text, '~') => out.push_str("\\textasciitilde{}"),
            (Mode::Text, '^') => out.push_str("\\textasciicircum{}"),
            (Mode::Text, '<') => out.push_str("\\textless{}"),
            (Mode::Text, '>') => out.push_str("\\textgreater{}"),
            (Mode::Text, '|') => out.push_str("\\textbar{}"),
            (Mode::Text, '"') => out.push_str(if opening { "``" } else { "''" }),
            (_, '{' | '}' | '$' | '&' | '%' | '#') | (Mode::Text, '_') => {
                out.push('\\');
                out.push(c);
            }
            (Mode::Math, '\\') => out.push_str("\\backslash "),
            (Mode::Math, '~') => out.push_str("\\sim "),
            (Mode::Math, c) if !c.is_ascii() => {
                let typed = c.to_string();
                match TYPED_MATH_MACROS.iter().find(|name| math_symbol(name) == Some(typed.as_str())) {
                    Some(name) => {
                        out.push('\\');
                        out.push_str(name);
                        out.push(' ');
                    }
                    None => out.push(c),
                }
            }
            _ => out.push(c),
        }
    }
    out
}

fn accent_base(body: &str) -> Option<String> {
    match body {
        "\\i" => Some("ı".into()),
        "\\j" => Some("ȷ".into()),
        b if b.chars().count() == 1 => Some(b.to_owned()),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn visible(src: &str) -> Vec<(String, &str)> {
        parse(src).units.iter().map(|u| (u.text.clone(), &src[u.range.clone()])).collect()
    }

    fn texts(src: &str) -> String {
        parse(src).units.iter().map(|u| u.text.as_str()).collect()
    }

    #[test]
    fn prose_ligature_input_and_quotes() {
        assert_eq!(texts("We write ``quotes'' -- and---dashes, `x'."), "Wewrite“quotes”–and—dashes,‘x’.");
        let units = visible("a--b");
        assert_eq!(units[1], ("–".to_owned(), "--"));
    }

    #[test]
    fn accents_compose_and_cover_the_macro() {
        let units = visible(r#"caf\'e na\"{\i}ve r\^ole \c{c}a"#);
        assert!(units.contains(&("é".into(), r"\'e")));
        assert!(units.contains(&("ï".into(), r#"\"{\i}"#)));
        assert!(units.contains(&("ô".into(), r"\^o")));
        assert!(units.contains(&("ç".into(), r"\c{c}")));
    }

    #[test]
    fn hidden_arguments_and_styled_content() {
        let src = r"See \emph{this} in Section~\ref{sec:x}\label{l} and \cite[p.~3]{knuth}.";
        assert_eq!(texts(src), "Seethisin Section".replace(' ', "") + "and.");
        let model = parse(src);
        let this = model.units.iter().find(|u| u.text == "t").unwrap();
        assert_eq!(this.construct, Construct::Styled);
    }

    #[test]
    fn math_symbols_and_modes() {
        let model = parse(r"Let $a^2 + b_i \leq \alpha$ and \[ \sum_{i=1}^{n} x' - 1 \]");
        let math: String = model.units.iter().filter(|u| u.mode == Mode::Math).map(|u| u.text.as_str()).collect();
        assert_eq!(math, "a2+bi≤α∑i=1nx′−1");
        assert!(model.units.iter().any(|u| u.construct == Construct::DisplayMath));
        let env = parse("\\begin{equation}\n E = mc^2 \\label{e}\n\\end{equation} after");
        let s: String = env.units.iter().map(|u| u.text.as_str()).collect();
        assert_eq!(s, "E=mc2after");
        assert_eq!(env.units.last().unwrap().mode, Mode::Text);
    }

    #[test]
    fn preamble_is_hidden_except_title_block_and_streams_are_separate() {
        let src = "\\documentclass{article}\n\\usepackage{x}\n\\title{My Title}\n\\begin{document}\nBody.\\footnote{Note.}\n\\end{document}\nignored";
        let model = parse(src);
        let main: String = model.units.iter().filter(|u| u.stream == 0).map(|u| u.text.as_str()).collect();
        assert_eq!(main, "Body.");
        assert_eq!(model.deferred_streams.len(), 1);
        let title: String =
            model.units.iter().filter(|u| u.stream == model.deferred_streams[0]).map(|u| u.text.as_str()).collect();
        assert_eq!(title, "MyTitle");
        let note: Vec<_> = model.units.iter().filter(|u| u.construct == Construct::Footnote).collect();
        assert_eq!(note.iter().map(|u| u.text.as_str()).collect::<String>(), "Note.");
        assert_eq!(note[0].line, 5);
    }

    #[test]
    fn typed_text_is_escaped_for_its_mode() {
        assert_eq!(
            escape_insertion("50% of {x} & $y_1$ ~ ^", Mode::Text),
            r"50\% of \{x\} \& \$y\_1\$ \textasciitilde{} \textasciicircum{}"
        );
        assert_eq!(escape_insertion("a\\b", Mode::Text), r"a\textbackslash{}b");
        // Shown as typed in every font encoding (OT1 has no < > | glyphs at
        // those positions and no straight double quote).
        assert_eq!(escape_insertion("a<b>c|d", Mode::Text), r"a\textless{}b\textgreater{}c\textbar{}d");
        assert_eq!(escape_insertion(r#""q" x"#, Mode::Text), r"``q'' x");
        assert_eq!(escape_insertion_after("\"", Mode::Text, Some('d')), "''");
        assert_eq!(escape_insertion_after("\"", Mode::Text, Some(' ')), "``");
        assert_eq!(escape_insertion("a<b", Mode::Math), "a<b");
        assert_eq!(escape_insertion("x_1^2 + α ≤ β", Mode::Math), r"x_1^2 + \alpha  \leq  \beta ");
        assert_eq!(escape_insertion("ε", Mode::Math), r"\varepsilon ");
        // What is inserted typesets as what was typed.
        for (typed, mode) in [("50% {x} & #", Mode::Text), ("α+β≤γ", Mode::Math)] {
            let escaped = escape_insertion(typed, mode);
            let src = if mode == Mode::Math { format!("${escaped}$") } else { escaped };
            let seen: String = parse(&src).units.iter().map(|u| u.text.as_str()).collect();
            assert_eq!(seen, typed.replace(' ', ""));
        }
    }

    #[test]
    fn math_regions_cover_delimiters() {
        let src = "a $x$ b \\[ y \\] c \\begin{align} z \\end{align} d";
        let model = parse(src);
        let regions: Vec<(&str, bool)> = model.math_regions.iter().map(|(r, b)| (&src[r.clone()], *b)).collect();
        assert_eq!(regions, [("$x$", false), ("\\[ y \\]", true), ("\\begin{align} z \\end{align}", true)]);
        let z = src.find('z').unwrap();
        assert_eq!(model.math_region_at(z).map(|(r, _)| &src[r.clone()]), Some("\\begin{align} z \\end{align}"));
    }

    #[test]
    fn comments_escapes_and_verbatim() {
        assert_eq!(texts("50\\% % comment\nok \\verb|a{b|"), "50%oka{b");
        assert_eq!(texts("x\\iffalse hidden\\fi y"), "xy");
    }
}
