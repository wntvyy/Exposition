//! A LaTeX *source model*: which characters of a source file are expected to
//! appear as glyphs on the page, what they look like, and which source range
//! produced each of them.
//!
//! This is deliberately not a TeX interpreter. It recognises the declared
//! construct set used for direct page editing — prose, TeX ligature input
//! (`--`, `---`, quotes), accent macros (`\'e`), escaped specials, styling
//! commands (`\emph{…}`), sectioning/caption/footnote arguments, inline and
//! display math with a macro → Unicode table — and treats everything else
//! conservatively: arguments of known non-printing commands (`\label`,
//! `\cite`, `\includegraphics`, …) produce nothing, unknown commands produce
//! nothing themselves while their brace arguments are treated as content.
//! Text generated by macros (numbers, citation labels, `\LaTeX`, user macro
//! bodies) has no source characters here, so it stays unmapped on the page.

use std::ops::Range;

use unicode_normalization::UnicodeNormalization;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize, ts_rs::TS)]
#[ts(export, rename = "TexSourceMode")]
#[serde(rename_all = "camelCase")]
pub enum Mode {
    Text,
    Math,
}

/// The construct a unit belongs to (for scope decisions and statistics).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize, ts_rs::TS)]
#[ts(export, rename = "TexConstruct")]
#[serde(rename_all = "camelCase")]
pub enum Construct {
    Prose,
    Styled,
    Heading,
    Caption,
    Footnote,
    Title,
    InlineMath,
    DisplayMath,
    Verbatim,
}

/// One source item that is expected to produce visible glyph(s).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SourceUnit {
    /// Expected visible text, NFC (e.g. "a", "é", "–", "α", "sin", "...").
    pub text: String,
    /// Byte range in the source text.
    pub range: Range<usize>,
    pub mode: Mode,
    pub construct: Construct,
    /// 0 for the main flow; other ids for content typeset elsewhere
    /// (footnotes, captions, title block).
    pub stream: u32,
    /// 1-based line of `range.start`.
    pub line: u32,
}

impl SourceUnit {
    /// A unit whose source is exactly its visible text (plain characters,
    /// directly editable character by character).
    pub fn is_literal(&self, source: &str) -> bool {
        source.get(self.range.clone()) == Some(self.text.as_str())
    }
}

/// The source model of one file.
#[derive(Clone, Debug, Default)]
pub struct SourceModel {
    pub units: Vec<SourceUnit>,
    /// Streams typeset away from their source position whose glyphs may be
    /// anywhere (title block: `\title`, `\author`, `\date`, `\thanks`).
    pub deferred_streams: Vec<u32>,
    /// 1-based inclusive line spans of constructs whose page content SyncTeX
    /// attributes to their *last* line (math, multi-line arguments).
    pub spans: Vec<(u32, u32)>,
    /// Byte ranges of math constructs including delimiters (`$…$`, `\[…\]`,
    /// `\begin{equation}…\end{equation}`), with whether each is a display.
    pub math_regions: Vec<(Range<usize>, bool)>,
}

impl SourceModel {
    /// The outermost math construct containing byte `offset`.
    pub fn math_region_at(&self, offset: usize) -> Option<&(Range<usize>, bool)> {
        self.math_regions.iter().filter(|(r, _)| r.start <= offset && offset < r.end).max_by_key(|(r, _)| r.len())
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum End {
    Eof,
    Brace,
    Bracket,
    Dollar,
    DoubleDollar,
    ParenMath,
    BracketMath,
    Env(usize, usize),
}

#[derive(Clone, Copy, Debug)]
struct Ctx {
    mode: Mode,
    construct: Construct,
    stream: u32,
    /// Units are kept even in the preamble (title block arguments).
    force_visible: bool,
    /// Units are discarded (invisible arguments).
    hidden: bool,
}

pub fn parse(source: &str) -> SourceModel {
    let mut parser = Parser {
        src: source,
        pos: 0,
        units: Vec::new(),
        deferred: Vec::new(),
        spans: Vec::new(),
        math_regions: Vec::new(),
        in_preamble: source.contains("\\begin{document}"),
        finished: false,
        line_starts: std::iter::once(0).chain(source.match_indices('\n').map(|(i, _)| i + 1)).collect(),
    };
    let ctx = Ctx { mode: Mode::Text, construct: Construct::Prose, stream: 0, force_visible: false, hidden: false };
    parser.run(ctx, End::Eof);
    SourceModel {
        units: parser.units,
        deferred_streams: parser.deferred,
        spans: parser.spans,
        math_regions: parser.math_regions,
    }
}

struct Parser<'a> {
    src: &'a str,
    pos: usize,
    units: Vec<SourceUnit>,
    deferred: Vec<u32>,
    spans: Vec<(u32, u32)>,
    math_regions: Vec<(Range<usize>, bool)>,
    in_preamble: bool,
    finished: bool,
    line_starts: Vec<usize>,
}

