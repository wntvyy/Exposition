impl Parser<'_> {
    fn peek(&self) -> Option<char> {
        self.src[self.pos..].chars().next()
    }

    fn peek_at(&self, offset: usize) -> Option<char> {
        self.src.get(self.pos + offset..).and_then(|s| s.chars().next())
    }

    fn line_of(&self, byte: usize) -> u32 {
        match self.line_starts.binary_search(&byte) {
            Ok(i) => i as u32 + 1,
            Err(i) => i as u32,
        }
    }

    fn emit(&mut self, ctx: Ctx, text: &str, range: Range<usize>) {
        if ctx.hidden || (self.in_preamble && !ctx.force_visible) || text.is_empty() {
            return;
        }
        let line = self.line_of(range.start);
        self.units.push(SourceUnit {
            text: text.nfc().collect(),
            range,
            mode: ctx.mode,
            construct: ctx.construct,
            stream: ctx.stream,
            line,
        });
    }

    fn skip_spaces(&mut self) {
        while let Some(c) = self.peek() {
            if c == '%' {
                self.skip_comment();
            } else if c.is_whitespace() {
                self.pos += c.len_utf8();
            } else {
                break;
            }
        }
    }

    fn skip_comment(&mut self) {
        match self.src[self.pos..].find('\n') {
            Some(i) => self.pos += i + 1,
            None => self.pos = self.src.len(),
        }
    }

    /// Skip a balanced `{…}` or `[…]` group starting at `pos`.
    fn skip_balanced(&mut self, open: char, close: char) {
        debug_assert_eq!(self.peek(), Some(open));
        let mut depth = 0usize;
        while let Some(c) = self.peek() {
            self.pos += c.len_utf8();
            match c {
                '\\' => {
                    if let Some(n) = self.peek() {
                        self.pos += n.len_utf8();
                    }
                }
                '%' => self.skip_comment(),
                c if c == open => depth += 1,
                c if c == close => {
                    depth -= 1;
                    if depth == 0 {
                        return;
                    }
                }
                _ => {}
            }
        }
    }

    fn read_control_name(&mut self) -> String {
        // pos is just after the backslash.
        let rest = &self.src[self.pos..];
        let letters: usize = rest.chars().take_while(|c| c.is_ascii_alphabetic()).map(char::len_utf8).sum();
        if letters > 0 {
            self.pos += letters;
            return rest[..letters].to_owned();
        }
        match rest.chars().next() {
            Some(c) => {
                self.pos += c.len_utf8();
                c.to_string()
            }
            None => String::new(),
        }
    }

    fn read_brace_word(&mut self) -> Option<String> {
        self.skip_spaces();
        if self.peek() != Some('{') {
            return None;
        }
        let start = self.pos + 1;
        self.skip_balanced('{', '}');
        Some(self.src[start..self.pos.saturating_sub(1)].trim().to_owned())
    }

    fn skip_star(&mut self) {
        if self.peek() == Some('*') {
            self.pos += 1;
        }
    }

    fn skip_optional_args(&mut self) {
        loop {
            let save = self.pos;
            self.skip_spaces();
            if self.peek() == Some('[') {
                self.skip_balanced('[', ']');
            } else {
                self.pos = save;
                return;
            }
        }
    }

    /// Skip `count` mandatory arguments (braced groups or single tokens) and
    /// any optional arguments around them.
    fn skip_args(&mut self, count: usize) {
        self.skip_star();
        self.skip_optional_args();
        for _ in 0..count {
            self.skip_spaces();
            match self.peek() {
                Some('{') => self.skip_balanced('{', '}'),
                Some('\\') => {
                    self.pos += 1;
                    self.read_control_name();
                }
                Some('[') => {}
                Some(c) => self.pos += c.len_utf8(),
                None => return,
            }
            self.skip_optional_args();
        }
    }

    /// Parse one brace argument as content in `ctx`.
    fn content_arg(&mut self, ctx: Ctx) {
        self.skip_spaces();
        if self.peek() == Some('{') {
            let start = self.pos;
            self.pos += 1;
            self.spanned(ctx, End::Brace, start);
        }
    }

    /// Run a nested construct and record its line span when it covers
    /// several lines.
    fn spanned(&mut self, ctx: Ctx, end: End, start: usize) {
        self.run(ctx, end);
        let (l0, l1) = (self.line_of(start), self.line_of(self.pos.saturating_sub(1).max(start)));
        if l1 > l0 {
            self.spans.push((l0, l1));
        }
        if ctx.mode == Mode::Math && end != End::Brace && end != End::Bracket {
            self.math_regions.push((start..self.pos, ctx.construct == Construct::DisplayMath));
        }
    }

    fn run(&mut self, ctx: Ctx, end: End) {
        while let Some(c) = self.peek() {
            if self.finished {
                return;
            }
            let start = self.pos;
            match c {
                '%' => self.skip_comment(),
                '{' => {
                    self.pos += 1;
                    self.run(ctx, End::Brace);
                }
                '}' => {
                    self.pos += 1;
                    if end == End::Brace {
                        return;
                    }
                }
                ']' if end == End::Bracket => {
                    self.pos += 1;
                    return;
                }
                '$' => {
                    let double = self.peek_at(1) == Some('$');
                    if ctx.mode == Mode::Math && matches!(end, End::Dollar | End::DoubleDollar) {
                        self.pos += if double && end == End::DoubleDollar { 2 } else { 1 };
                        return;
                    }
                    if double {
                        self.pos += 2;
                        let math = Ctx { mode: Mode::Math, construct: Construct::DisplayMath, ..ctx };
                        self.spanned(math, End::DoubleDollar, start);
                    } else {
                        self.pos += 1;
                        let math = Ctx { mode: Mode::Math, construct: Construct::InlineMath, ..ctx };
                        self.spanned(math, End::Dollar, start);
                    }
                }
                '\\' => {
                    self.pos += 1;
                    if self.command(ctx, end, start) {
                        return;
                    }
                }
                '~' | '&' | '#' => self.pos += 1,
                '^' | '_' if ctx.mode == Mode::Math => self.pos += 1,
                c if c.is_whitespace() => self.pos += c.len_utf8(),
                _ => self.literal(ctx),
            }
        }
    }

    fn literal(&mut self, ctx: Ctx) {
        let start = self.pos;
        let rest = &self.src[self.pos..];
        let c = rest.chars().next().expect("literal at end");
        if ctx.mode == Mode::Math {
            self.pos += c.len_utf8();
            self.absorb_combining_marks();
            let text = match c {
                '-' => "−".to_owned(),
                '\'' => "′".to_owned(),
                '*' => "∗".to_owned(),
                _ => self.src[start..self.pos].to_owned(),
            };
            self.emit(ctx, &text, start..self.pos);
            return;
        }
        let (text, len): (&str, usize) = if rest.starts_with("---") {
            ("—", 3)
        } else if rest.starts_with("--") {
            ("–", 2)
        } else if rest.starts_with("``") {
            ("“", 2)
        } else if rest.starts_with("''") {
            ("”", 2)
        } else if rest.starts_with("!`") {
            ("¡", 2)
        } else if rest.starts_with("?`") {
            ("¿", 2)
        } else if c == '`' {
            ("‘", 1)
        } else if c == '\'' {
            ("’", 1)
        } else {
            self.pos += c.len_utf8();
            self.absorb_combining_marks();
            let text = self.src[start..self.pos].to_owned();
            self.emit(ctx, &text, start..self.pos);
            return;
        };
        self.pos += len;
        self.emit(ctx, text, start..self.pos);
    }

    /// Combining marks after a character render with it (`e` + U+0301 is
    /// one `é`): they belong to its unit.
    fn absorb_combining_marks(&mut self) {
        while let Some(c) = self.peek().filter(|&c| unicode_normalization::char::is_combining_mark(c)) {
            self.pos += c.len_utf8();
        }
    }

    /// An empty group right after a symbol command (`\ldots{}`,
    /// `\textasciitilde{}`) only terminates it: it belongs to its unit.
    fn absorb_empty_group(&mut self) {
        if self.src[self.pos..].starts_with("{}") {
            self.pos += 2;
        }
    }

    /// Handle a control sequence (backslash already consumed). Returns true
    /// when it closes the current `end`.
    fn command(&mut self, ctx: Ctx, end: End, start: usize) -> bool {
        let name = self.read_control_name();
        match name.as_str() {
            "" => {}
            "(" => {
                let math = Ctx { mode: Mode::Math, construct: Construct::InlineMath, ..ctx };
                self.spanned(math, End::ParenMath, start);
            }
            ")" => return end == End::ParenMath,
            "[" => {
                let math = Ctx { mode: Mode::Math, construct: Construct::DisplayMath, ..ctx };
                self.spanned(math, End::BracketMath, start);
            }
            "]" => return end == End::BracketMath,
            "begin" => {
                let Some(env) = self.read_brace_word() else { return false };
                return self.begin_env(ctx, &env, start);
            }
            "end" => {
                let Some(env) = self.read_brace_word() else { return false };
                if env == "document" {
                    self.finished = true;
                    return true;
                }
                if let End::Env(a, b) = end
                    && self.src[a..b] == env
                {
                    return true;
                }
            }
            "%" | "&" | "$" | "#" | "_" | "{" | "}" => self.emit(ctx, &name, start..self.pos),
            " " | "," | ";" | ":" | "!" | ">" | "<" | "-" | "/" | "@" | "\n" | "\r" | "\t" => {}
            "\\" => {
                self.skip_star();
                self.skip_optional_args();
            }
            "|" if ctx.mode == Mode::Math => self.emit(ctx, "‖", start..self.pos),
            "verb" => {
                self.skip_star();
                if let Some(delim) = self.peek() {
                    self.pos += delim.len_utf8();
                    let body_end = self.src[self.pos..].find(delim).map(|i| self.pos + i).unwrap_or(self.src.len());
                    let verb = Ctx { construct: Construct::Verbatim, ..ctx };
                    while self.pos < body_end {
                        let c = self.peek().expect("inside verb");
                        let s = self.pos;
                        self.pos += c.len_utf8();
                        if !c.is_whitespace() {
                            self.emit(verb, &c.to_string(), s..self.pos);
                        }
                    }
                    self.pos = (body_end + delim.len_utf8()).min(self.src.len());
                }
            }
            "url" | "nolinkurl" | "path" => {
                self.skip_spaces();
                if self.peek() == Some('{') {
                    let body_start = self.pos + 1;
                    self.skip_balanced('{', '}');
                    let body_end = self.pos - 1;
                    let verb = Ctx { construct: Construct::Verbatim, ..ctx };
                    let mut p = body_start;
                    for c in self.src[body_start..body_end].chars() {
                        let s = p;
                        p += c.len_utf8();
                        self.emit(verb, &c.to_string(), s..p);
                    }
                }
            }
            "href" => {
                self.skip_args(1);
                self.content_arg(ctx);
            }
            "textcolor" | "colorbox" => {
                self.skip_args(1);
                self.content_arg(ctx);
            }
            "footnote" | "footnotetext" | "caption" | "marginpar" => {
                self.skip_star();
                self.skip_optional_args();
                let construct = if name == "caption" { Construct::Caption } else { Construct::Footnote };
                let stream = start as u32 + 1;
                self.content_arg(Ctx { construct, stream, mode: Mode::Text, ..ctx });
            }
            "title" | "author" | "date" | "thanks" => {
                self.skip_optional_args();
                let stream = start as u32 + 1;
                self.deferred.push(stream);
                self.content_arg(Ctx {
                    construct: Construct::Title,
                    stream,
                    mode: Mode::Text,
                    force_visible: true,
                    ..ctx
                });
            }
            "def" | "gdef" | "edef" | "xdef" => {
                self.skip_spaces();
                if self.peek() == Some('\\') {
                    self.pos += 1;
                    self.read_control_name();
                }
                while let Some(c) = self.peek() {
                    if c == '{' {
                        break;
                    }
                    self.pos += c.len_utf8();
                }
                if self.peek() == Some('{') {
                    self.skip_balanced('{', '}');
                }
            }
            "let" => {
                self.skip_spaces();
                for _ in 0..2 {
                    self.skip_spaces();
                    if self.peek() == Some('=') {
                        self.pos += 1;
                        self.skip_spaces();
                    }
                    if self.peek() == Some('\\') {
                        self.pos += 1;
                        self.read_control_name();
                    } else if let Some(c) = self.peek() {
                        self.pos += c.len_utf8();
                    }
                }
            }
            "iffalse" => match self.src[self.pos..].find("\\fi") {
                Some(i) => self.pos += i + 3,
                None => self.pos = self.src.len(),
            },
            "item" => {
                self.skip_spaces();
                if self.peek() == Some('[') {
                    self.pos += 1;
                    self.run(ctx, End::Bracket);
                }
            }
            "sqrt" if ctx.mode == Mode::Math => {
                self.emit(ctx, "√", start..self.pos);
                self.skip_spaces();
                if self.peek() == Some('[') {
                    self.pos += 1;
                    self.run(ctx, End::Bracket);
                }
            }
            n if ctx.mode == Mode::Math && text_in_math(n) => {
                self.content_arg(Ctx { mode: Mode::Text, ..ctx });
            }
            n if hidden_args(n).is_some() => {
                let count = hidden_args(n).unwrap_or(0);
                self.skip_args(count);
            }
            n if heading(n) => {
                self.skip_star();
                self.skip_optional_args();
                self.content_arg(Ctx { construct: Construct::Heading, ..ctx });
            }
            n if styled(n) => {
                self.skip_optional_args();
                let construct = if ctx.construct == Construct::Prose { Construct::Styled } else { ctx.construct };
                self.content_arg(Ctx { construct, ..ctx });
            }
            n if accent_mark(n).is_some() && (ctx.mode == Mode::Text || n.len() > 1) => {
                self.accent(ctx, n, start);
            }
            n if ctx.mode == Mode::Math && math_symbol(n).is_some() => {
                let text = math_symbol(n).unwrap_or_default();
                self.absorb_empty_group();
                self.emit(ctx, text, start..self.pos);
            }
            n if text_symbol(n).is_some() => {
                let text = text_symbol(n).unwrap_or_default();
                self.absorb_empty_group();
                self.emit(ctx, text, start..self.pos);
            }
            n if silent(n) => {}
            _ => {
                // Unknown command: typesets nothing we can predict; its brace
                // arguments are parsed as content by the main loop.
            }
        }
        false
    }

    fn begin_env(&mut self, ctx: Ctx, env: &str, begin: usize) -> bool {
        if env == "document" {
            self.in_preamble = false;
            return false;
        }
        if matches!(env, "verbatim" | "verbatim*" | "lstlisting" | "minted" | "comment") {
            let end_marker = format!("\\end{{{env}}}");
            let body_end = self.src[self.pos..].find(&end_marker).map(|i| self.pos + i).unwrap_or(self.src.len());
            if env != "comment" {
                let verb = Ctx { construct: Construct::Verbatim, ..ctx };
                let mut p = self.pos;
                for c in self.src[self.pos..body_end].chars() {
                    let s = p;
                    p += c.len_utf8();
                    if !c.is_whitespace() {
                        self.emit(verb, &c.to_string(), s..p);
                    }
                }
            }
            self.pos = (body_end + end_marker.len()).min(self.src.len());
            return false;
        }
        if MATH_ENVS.contains(&env) {
            let name_end = self.pos - 1;
            let name_start = name_end - env.len();
            if env_args(env) > 0 {
                self.skip_args(env_args(env));
            }
            let construct = if env == "math" { Construct::InlineMath } else { Construct::DisplayMath };
            let math = Ctx { mode: Mode::Math, construct, ..ctx };
            // The name sits inside the braces just consumed: locate it for the End marker.
            let located = self.src[..=name_end.min(self.src.len() - 1)]
                .rfind(env)
                .map(|i| (i, i + env.len()))
                .unwrap_or((name_start, name_end));
            self.spanned(math, End::Env(located.0, located.1), begin);
            return false;
        }
        self.skip_optional_args();
        if env_args(env) > 0 {
            self.skip_args(env_args(env));
        }
        false
    }

    fn accent(&mut self, ctx: Ctx, name: &str, start: usize) {
        let mark = accent_mark(name).expect("accent");
        // Argument: {x}, {\i}, x, or \i.
        if name.chars().all(|c| c.is_ascii_alphabetic()) {
            self.skip_spaces();
        }
        let base: Option<String> = match self.peek() {
            Some('{') => {
                let body_start = self.pos + 1;
                self.skip_balanced('{', '}');
                let body = self.src[body_start..self.pos - 1].trim();
                accent_base(body)
            }
            Some('\\') => {
                self.pos += 1;
                let n = self.read_control_name();
                accent_base(&format!("\\{n}"))
            }
            Some(c) => {
                self.pos += c.len_utf8();
                Some(c.to_string())
            }
            None => None,
        };
        if let Some(base) = base {
            let base = match base.as_str() {
                "ı" => "i".to_owned(),
                "ȷ" => "j".to_owned(),
                _ => base,
            };
            let composed: String = format!("{base}{mark}").nfc().collect();
            self.emit(ctx, &composed, start..self.pos);
        }
    }
}

