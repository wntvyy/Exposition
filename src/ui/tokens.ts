// Design token names and resolved values for TypeScript consumers.
//
// `tokens.css` is what styles the application; this module mirrors it so code
// that cannot read CSS custom properties (the Monaco theme, canvas renderers,
// tests) uses the same values. `tokens.test.ts` fails if the two drift and
// checks WCAG contrast for the documented pairs in both themes.
//
// In components prefer CSS classes or `var(--token)` strings (see `cssVar`) over
// literal values, so theme switches apply without re-rendering.

