/** Resolved color values per theme (aliases already resolved). */
export const palettes: Record<ThemeName, Record<ColorRole, string>> = { light, dark };

/** `var(--color-<role>)` for inline styles. */
export function colorVar(role: ColorRole): string {
  return `var(--color-${role})`;
}

