// Design token names and resolved values for TypeScript consumers.
//
// `tokens.css` is what styles the application; this module mirrors it so code
// that cannot read CSS custom properties (the Monaco theme, canvas renderers,
// tests) uses the same values. `tokens.test.ts` fails if the two drift and
// checks WCAG contrast for the documented pairs in every theme.
//
// The four built-in themes (UI standard V2, palettes approved 2026-11-19): each
// uses one muted accent and four semantic hues (info, success, warning, danger);
// stale status follows the warning colors; graph categories reuse those hues
// plus one muted violet for math nodes.
//
// In components prefer CSS classes or `var(--token)` strings (see `cssVar`) over
// literal values, so theme switches apply without re-rendering.

export type ThemeName = "light" | "dark" | "ocean" | "sage";

/** The built-in themes, in the order Settings lists them. */
