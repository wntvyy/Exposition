// The list of what a Checked result verified: declarations written in the
// text first (in text order, each jumping to its name), then the ones Lean
// generated in a collapsed section that opens from the keyboard.
import { cleanup, fireEvent, render, screen, within } from "@testing-library/react";
import { afterEach, describe, expect, it, vi } from "vitest";

import type { CheckedDeclaration } from "../../bindings/CheckedDeclaration";
import type { LeanDocumentState } from "../../bindings/LeanDocumentState";

const monaco = vi.hoisted(() => ({ revealInEditor: vi.fn() }));
vi.mock("./leanMonaco", () => monaco);

const { CheckedDeclarations } = await import("./CheckedDeclarations");

const declarations: CheckedDeclaration[] = [
  {
    name: "Paper.sumTo",
    kind: "def",
    statement: "Nat → Nat",
    range: { start: 30, end: 35 },
    line: 4,
    axioms: [],
  },
  {
    name: "Paper.two_mul_sumTo",
    kind: "theorem",
    statement: "∀ (n : Nat), 2 * Paper.sumTo n = n * (n + 1)",
    range: { start: 120, end: 133 },
    line: 9,
    axioms: ["Classical.choice", "Quot.sound", "propext"],
  },
  { name: "Paper.sumTo.eq_1", kind: "theorem", statement: "Paper.sumTo 0 = 0", range: null, line: null, axioms: [] },
];

const state = { document: "d1", path: "Paper/Gauss.lean", revision: 7 } as unknown as LeanDocumentState;

describe("CheckedDeclarations", () => {
  afterEach(() => {
    cleanup();
    monaco.revealInEditor.mockReset();
  });

  it("lists the written declarations with their statements and axioms, and reveals one", () => {
    render(<CheckedDeclarations state={state} declarations={declarations} total={3} />);
    const written = screen.getByRole("list", { name: "Declarations in the text" });
    const rows = within(written).getAllByTestId("lean-checked-declaration");
    expect(rows.map((r) => r.getAttribute("data-name"))).toEqual(["Paper.sumTo", "Paper.two_mul_sumTo"]);
    expect(rows[1]!.textContent).toContain("∀ (n : Nat), 2 * Paper.sumTo n = n * (n + 1)");
    expect(rows[1]!.textContent).toContain("Axioms: Classical.choice, Quot.sound, propext");
    expect(rows[0]!.textContent).toContain("No axioms");
    const jump = within(rows[1]!).getByRole("button", { name: /theorem Paper\.two_mul_sumTo, line 10: show in editor/ });
    fireEvent.click(jump);
    expect(monaco.revealInEditor).toHaveBeenCalledWith("Paper/Gauss.lean", { range: { start: 120, end: 133 } });
    expect(screen.getByText(/Checked declarations \(3\)/)).toBeTruthy();
  });

  it("keeps generated declarations collapsed behind a native disclosure button", () => {
    render(<CheckedDeclarations state={state} declarations={declarations} total={3} />);
    const toggle = screen.getByRole("button", { name: /Generated by Lean \(1\)/ });
    expect(toggle.tagName).toBe("BUTTON"); // Enter and Space activate it
    expect(toggle.getAttribute("aria-expanded")).toBe("false");
    expect(screen.getByTestId("lean-checked-generated").closest("[hidden]")).not.toBeNull();
    fireEvent.click(toggle);
    expect(toggle.getAttribute("aria-expanded")).toBe("true");
    expect(screen.getByTestId("lean-checked-generated").closest("[hidden]")).toBeNull();
    // A generated declaration has no place in the text to jump to.
    expect(within(screen.getByTestId("lean-checked-generated")).getByRole("button").hasAttribute("disabled")).toBe(true);
  });

  it("says how many were not listed", () => {
    render(<CheckedDeclarations state={state} declarations={declarations} total={340} />);
    expect(screen.getByTestId("lean-checked-more").textContent).toBe("337 more checked declarations are not listed.");
  });
});
