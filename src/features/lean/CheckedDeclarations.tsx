// What a Checked Lean result verified, listed under the status in the Lean
// infoview (see LeanPanel).
import type { CheckedDeclaration } from "../../bindings/CheckedDeclaration";
import type { LeanDocumentState } from "../../bindings/LeanDocumentState";
import { Section } from "../../ui/components";
import { revealInEditor } from "./leanMonaco";

/**
 * What a Checked result verified: each declaration of the revision, kernel-
 * checked in the audit's own elaboration of the text, with its type as the
 * audit printed it (the toolchain's notation, none of the project's) and the
 * axioms it uses. Declarations written in the text come first; those Lean
 * generated (equation lemmas, recursors, ...) are in a collapsed section.
 */
export function CheckedDeclarations({
  state,
  declarations,
  total,
}: {
  state: LeanDocumentState;
  declarations: CheckedDeclaration[];
  total: number;
}) {
  const written = declarations.filter((d) => d.range);
  const generated = declarations.filter((d) => !d.range);
  return (
    <Section title={`Checked declarations (${total})`}>
      <div data-testid="lean-checked-declarations" className="exp-lean__checked">
        <p className="exp-muted exp-lean__note">
          Re-checked by Lean’s kernel in the audit’s own elaboration of revision {state.revision}. Types are printed
          by the audit, without the project’s notation.
        </p>
        {written.length > 0 ? (
          <ul className="exp-lean__list" aria-label="Declarations in the text">
            {written.map((d) => (
              <CheckedDeclarationRow key={d.name} state={state} d={d} />
            ))}
          </ul>
        ) : (
          <p className="exp-muted">No declaration in the text.</p>
        )}
        {generated.length > 0 && (
          <Section title={`Generated by Lean (${generated.length})`} collapsible defaultExpanded={false}>
            <ul className="exp-lean__list" aria-label="Declarations Lean generated" data-testid="lean-checked-generated">
              {generated.map((d) => (
                <CheckedDeclarationRow key={d.name} state={state} d={d} />
              ))}
            </ul>
          </Section>
        )}
        {total > declarations.length && (
          <p className="exp-muted" data-testid="lean-checked-more">
            {total - declarations.length} more checked declarations are not listed.
          </p>
        )}
      </div>
    </Section>
  );
}

function CheckedDeclarationRow({ state, d }: { state: LeanDocumentState; d: CheckedDeclaration }) {
  const range = d.range;
  return (
    <li className="exp-lean__decl" data-testid="lean-checked-declaration" data-name={d.name}>
      <button
        type="button"
        className="exp-lean__diag-jump"
        disabled={!range}
        aria-label={range ? `${d.kind} ${d.name}, line ${(d.line ?? 0) + 1}: show in editor` : `${d.kind} ${d.name}`}
        onClick={() => range && void revealInEditor(state.path, { range })}
      >
        <span className="exp-lean__kind">{d.kind}</span>
        {d.line != null && <span className="exp-lean__line">Ln {d.line + 1}</span>}
        <code>{d.name}</code>
      </button>
      <pre className="exp-lean__message">{d.statement}</pre>
      <p className="exp-lean__decl-axioms exp-muted">
        {d.axioms.length ? `Axioms: ${d.axioms.join(", ")}` : "No axioms"}
      </p>
    </li>
  );
}
