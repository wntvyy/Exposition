import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

import { listedCommands, stalePermissionFiles } from "./check-permissions.mjs";

const BUILD_RS = `
const COMMANDS: &[&str] = &[
    "app_info",
    // Workspace (src/workspace.rs).
    "workspace_open", // "not_a_command" in a comment
];
const DEV_COMMANDS: &[&str] = &["dev_start_probe_job"];
`;

describe("stalePermissionFiles", () => {
  it("reads both command lists and ignores comments", () => {
    expect([...listedCommands(BUILD_RS)]).toEqual(["app_info", "workspace_open", "dev_start_probe_job"]);
  });

  it("flags files of commands that are not listed", () => {
    const files = ["app_info.toml", "workspace_open.toml", "dev_start_probe_job.toml", "removed_command.toml", "notes.md"];
    expect(stalePermissionFiles(BUILD_RS, files)).toEqual(["removed_command.toml"]);
  });

  it("finds no stale file in this repository", () => {
    const root = join(import.meta.dirname, "..");
    const buildRs = readFileSync(join(root, "src-tauri", "build.rs"), "utf8");
    const files = readdirSync(join(root, "src-tauri", "permissions", "autogenerated"));
    expect(stalePermissionFiles(buildRs, files)).toEqual([]);
  });
});
